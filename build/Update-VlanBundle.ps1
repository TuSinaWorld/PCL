[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$ClientExePath,
    [Parameter(Mandatory=$true)][string]$WintunDirectory,
    [Parameter(Mandatory=$true)][string]$VlanSourceRoot
)
$ErrorActionPreference='Stop'
$repoRoot=Split-Path $PSScriptRoot -Parent
$exe=(Resolve-Path -LiteralPath $ClientExePath).Path
$wintun=(Resolve-Path -LiteralPath $WintunDirectory).Path
$source=(Resolve-Path -LiteralPath $VlanSourceRoot).Path
$version=& $exe --version
if($LASTEXITCODE -ne 0 -or $version -notmatch 'protocol=9.*machine=1') { throw 'Expected a successfully built v9 CLI with machine interface v1.' }
$stage=Join-Path ([IO.Path]::GetTempPath()) ('pcl-vlan-package-'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $stage | Out-Null
Copy-Item -LiteralPath $exe -Destination (Join-Path $stage 'vlan-cli.exe')
Copy-Item -LiteralPath (Join-Path $wintun 'bin\amd64\wintun.dll') -Destination $stage
Copy-Item -LiteralPath (Join-Path $source 'LICENSE'),(Join-Path $source 'NOTICE') -Destination $stage
$notices=Join-Path $stage 'wintun-notices'
New-Item -ItemType Directory -Path $notices | Out-Null
Copy-Item -LiteralPath (Join-Path $wintun 'LICENSE.txt'),(Join-Path $wintun 'README.md'),(Join-Path $wintun 'include\wintun.h') -Destination $notices
$version | Set-Content -LiteralPath (Join-Path $stage 'component-version.txt') -Encoding utf8
$archive=Join-Path $repoRoot 'Plain Craft Launcher 2\Resources\VLanBundle.zip'
Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $archive -Force
$hash=(Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
$module=Join-Path $repoRoot 'Plain Craft Launcher 2\Modules\ModVlanPackage.vb'
$text="' Generated by build/Update-VlanBundle.ps1; source and third-party notices are in the package.`r`nFriend Module ModVlanPackage`r`n    Friend Const BundleSha256 As String = ""$hash""`r`nEnd Module`r`n"
[IO.File]::WriteAllText($module,$text,[Text.UTF8Encoding]::new($false))
[pscustomobject]@{Version=$version;Bundle=$archive;Sha256=$hash}
